export function nationNameToFlagEmoji(nationName: string): string {
  const key = nationName.trim()
  if (!key) return ''
  const iso = NATION_NAME_TO_ISO[key] ?? NATION_NAME_TO_ISO[key.replace(/\s+/g, ' ')]
  if (!iso) return ''
  return isoCountryCodeToFlag(iso)
}

/** Split `Italy / Argentina` style display into nation labels. */
export function splitNationDisplay(nationDisplay: string): string[] {
  return nationDisplay
    .split('/')
    .map((s) => s.trim())
    .filter(Boolean)
}
