/** ISO 3166-1 alpha-2 → regional indicator flag emoji. */
export function isoCountryCodeToFlag(iso: string): string {
  const cc = iso.trim().toUpperCase()
  if (!/^[A-Z]{2}$/.test(cc)) return ''
  const base = 0x1f1e6
  return [...cc].map((c) => String.fromCodePoint(base + c.charCodeAt(0) - 65)).join('')
}

